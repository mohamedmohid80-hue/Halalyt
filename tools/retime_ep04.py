"""Map the episode 4 animation timeline (built on the first voiceover) onto a new recording.

    python3 tools/retime_ep04.py audio/04-delaying-salah-v2.words.json [more parts...]

Parts are appended in order (each part's words are offset by the previous parts' durations,
read from the matching .mp3). Words are aligned to the original recording; matched word starts
become anchors of a piecewise-linear map, written to remotion/ep4/timemap.js.
"""
import difflib, json, re, subprocess, sys
from pathlib import Path
R = Path(__file__).resolve().parent.parent
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower()).replace("duhur", "dhuhr").replace("duhr", "dhuhr").replace("vuhr", "dhuhr")
old = json.load(open(R / "audio/04-delaying-salah.words.json"))
new, off, files = [], 0.0, []
for p in sys.argv[1:]:
    ws = json.load(open(p))
    new += [[w[0], w[1] + off, w[2] + off] for w in ws]
    mp3 = p.replace(".words.json", ".mp3")
    files.append([Path(mp3).name, round(off, 3)])
    off += float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", mp3]))
sm = difflib.SequenceMatcher(None, [norm(w[0]) for w in old], [norm(w[0]) for w in new], autojunk=False)
anchors = [[0.0, 0.0]]
for b in sm.get_matching_blocks():
    for k in range(b.size):
        o, n = old[b.a + k][1], new[b.b + k][1]
        if o > anchors[-1][0] + 0.05 and n > anchors[-1][1] + 0.05:
            anchors.append([round(o, 3), round(n, 3)])
last_old = old[-1][2]
covered = anchors[-1][0]
anchors.append([round(last_old + 0.6, 3), round(anchors[-1][1] + (last_old + 0.6 - anchors[-1][0]), 3)])
(R / "remotion/ep4/timemap.js").write_text(
    "// generated by tools/retime_ep04.py: [original-voiceover time, new-voiceover time]\n"
    f"const TMAP = {json.dumps(anchors)};\nconst VO_PARTS = {json.dumps(files)};\nconst VO_TOTAL = {round(off, 3)};\n")
print(f"{len(anchors)} anchors; new audio {off:.1f}s; original covered up to {covered:.1f}s of {last_old:.1f}s")
